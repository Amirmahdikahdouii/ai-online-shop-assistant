import { expect, test } from "@playwright/test";
import { randomUUID } from "node:crypto";

for (const width of [360, 1280]) test(`review changes and approve with stale revision at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 960 });
  await page.goto("/login");
  const origin = new URL(page.url()).origin;
  const credentials = { username: `apr_${randomUUID().replaceAll("-", "").slice(0, 12)}`, password: "approval-password-123" };
  expect((await page.request.post("/api/auth/register", { data: credentials })).status()).toBe(201);
  expect((await page.request.post("/api/auth/login", { headers: { Origin: origin }, data: credentials })).status()).toBe(200);
  const me = await (await page.request.get("/api/me")).json();
  const headers = { Origin: origin, "X-CSRF-Token": me.csrfToken };
  const { store } = await (await page.request.post("/api/stores", { headers, data: { name: "پوشاک نارون" } })).json();
  const base = `/api/stores/${store.id}/products`;
  const { product } = await (await page.request.post(base, { headers, data: { name: "مانتو لینن", variants: [{ name: "زیتونی متوسط", price: null, attributes: { رنگ: "زیتونی" } }] } })).json();
  await page.goto("/dashboard/products");
  await page.getByRole("button", { name: "مشاهده و ویرایش" }).click();
  const editor = page.getByRole("region", { name: "فرم محصول" });
  const approve = editor.getByRole("button", { name: "تأیید صریح محصول ذخیره‌شده" });
  await expect(editor.getByText("تا تأیید شما، این محصول قلم قطعی سفارش نیست.")).toBeVisible();
  await page.getByLabel("نام تنوع", { exact: true }).fill("  ");
  await expect(page.getByLabel("نام تنوع", { exact: true })).toHaveAttribute("aria-invalid", "true");
  await expect(editor.getByText("نام تنوع را کامل وارد کنید.", { exact: true })).toBeVisible();
  await expect(approve).toBeDisabled();
  await editor.screenshot({ path: `test-results/approval-validation-${width}.png` });
  await page.getByLabel("نام تنوع", { exact: true }).fill("زیتونی بزرگ");
  const changes = editor.getByRole("region", { name: "خلاصهٔ تغییرات" });
  await expect(changes).toContainText("زیتونی متوسط");
  await expect(changes).toContainText("زیتونی بزرگ");
  await changes.screenshot({ path: `test-results/approval-changes-${width}.png` });
  await expect(approve).toBeDisabled();
  await page.getByRole("button", { name: "ذخیره محصول", exact: true }).click();
  await expect(editor.getByRole("region", { name: "خلاصهٔ پیش از تأیید" })).toContainText("قیمت نامعلوم");
  await expect(approve).toBeEnabled();
  let release!: () => void;
  const pending = new Promise<void>(resolve => { release = resolve; });
  await page.route(`**${base}/${product.id}/approve`, async route => { await pending; await route.abort(); });
  await approve.dblclick({ force: true });
  await expect(approve).toBeDisabled();
  release();
  await expect(page.locator(".catalog [role=alert]")).toContainText("ارتباط برقرار نشد");
  await expect(page.locator(".catalog [role=status]")).toHaveCount(0);
  await expect(approve).toBeEnabled();
  await page.unroute(`**${base}/${product.id}/approve`);
  // An actual concurrent edit makes the displayed revision stale.
  const fresh = (await (await page.request.get(`${base}/${product.id}`)).json()).product;
  expect((await page.request.post(`${base}/${product.id}`, { headers, data: { name: "مانتو اصلاح‌شده", variants: fresh.variants, revision: fresh.revision } })).status()).toBe(200);
  await approve.click();
  await expect(page.locator(".catalog [role=alert]")).toContainText("نسخهٔ محصول تغییر کرده است");
  await expect(page.getByLabel("نام تنوع", { exact: true })).toHaveValue("زیتونی بزرگ");
  await editor.getByRole("button", { name: "بارگیری مجدد محصول و تاریخچه" }).click();
  await expect(page.getByLabel("نام محصول", { exact: true })).toHaveValue("مانتو اصلاح‌شده");
  await approve.focus(); await page.keyboard.press("Enter");
  await expect(page.locator(".catalog [role=status]")).toHaveText("محصول تأیید شد.");
  await expect(editor.getByText("تأییدشده؛ قابل انتخاب به‌عنوان قلم قطعی سفارش.")).toBeVisible();
  const detail = await (await page.request.get(`${base}/${product.id}`)).json();
  expect(detail.product.status).toBe("approved"); expect(detail.product.variants[0].price).toBeNull();
  expect(detail.history).toHaveLength(4);
  expect(detail.history[3].actorId).toBe(me.user.id); expect(detail.history[3].changedAt).toBeTruthy();
  await editor.getByText("تاریخچهٔ تغییرات", { exact: true }).click();
  await expect(editor.locator("details")).toContainText(me.user.id);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: `test-results/approval-${width}.png`, fullPage: true });
});
