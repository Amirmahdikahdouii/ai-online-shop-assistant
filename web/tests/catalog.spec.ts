import { expect, test } from "@playwright/test";
import { randomUUID } from "node:crypto";

for (const width of [360, 1280]) test(`manual catalog lifecycle at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 960 });
  await page.goto("/login");
  const headers = { Origin: new URL(page.url()).origin };
  const credentials = { username: `cat_${randomUUID().replaceAll("-", "").slice(0, 12)}`, password: "catalog-password-12345" };
  expect((await page.request.post("/api/auth/register", { data: credentials })).status()).toBe(201);
  expect((await page.request.post("/api/auth/login", { headers, data: credentials })).status()).toBe(200);
  const me = await (await page.request.get("/api/me")).json();
  const mutationHeaders = { ...headers, "X-CSRF-Token": me.csrfToken };
  const store = await (await page.request.post("/api/stores", { headers: mutationHeaders, data: { name: "پوشاک نارون" } })).json();
  const base = `/api/stores/${store.store.id}/products`;
  expect((await page.request.post(base, { headers, data: { name: "forbidden" } })).status()).toBe(403);
  let release!: () => void; const pending = new Promise<void>(resolve => { release = resolve; });
  await page.route("**/api/stores/*/products?*", async route => { await pending; await route.continue(); });
  await page.goto("/dashboard/products");
  await expect(page.getByRole("region", { name: "کاتالوگ محصولات" }).getByRole("status")).toContainText("در حال دریافت محصولات"); release();
  await expect(page.getByRole("heading", { name: "محصولی پیدا نشد" })).toBeVisible();
  await page.unroute("**/api/stores/*/products?*");
  await page.getByRole("button", { name: "ثبت محصول دستی" }).click();
  await page.getByLabel("نام محصول", { exact: true }).fill("پیراهن لینن");
  await page.getByLabel("نام تنوع", { exact: true }).fill("آبی متوسط");
  await page.getByLabel("کد اختیاری").fill("LINEN-BLUE");
  await page.getByRole("button", { name: "افزودن ویژگی" }).click();
  await page.getByLabel("نام ویژگی").fill("رنگ"); await page.getByLabel("مقدار ویژگی").fill("آبی");
  await page.getByRole("button", { name: "افزودن ویژگی" }).click();
  await page.getByLabel("نام ویژگی").nth(1).fill("رنگ");
  await page.getByLabel("مقدار ویژگی").nth(1).fill("متوسط");
  await page.getByRole("button", { name: "ذخیره محصول", exact: true }).click();
  await expect(page.locator(".catalog [role=alert]")).toContainText("نام ویژگی‌ها تکراری است");
  await expect(page.getByLabel("مقدار ویژگی").nth(0)).toHaveValue("آبی");
  await expect(page.getByLabel("مقدار ویژگی").nth(1)).toHaveValue("متوسط");
  await page.getByRole("button", { name: "حذف ویژگی" }).nth(1).click();
  await expect(page.getByLabel("نام ویژگی")).toHaveAttribute("aria-invalid", "false");
  await page.getByRole("button", { name: "افزودن تنوع", exact: true }).click();
  await page.getByLabel("نام تنوع", { exact: true }).nth(1).fill("سفید بزرگ");
  await page.getByLabel("قیمت نامعلوم").nth(1).uncheck();
  await expect(page.getByLabel("قیمت به تومان").nth(1)).toHaveValue("");
  await expect(page.getByLabel("قیمت به تومان").nth(1)).toHaveAttribute("required", "");
  await page.getByLabel("قیمت به تومان").nth(1).fill("480000");
  let finish!: () => void; const failure = new Promise<void>(resolve => { finish = resolve; }); let calls = 0;
  await page.route(`**${base}`, async route => { calls++; await failure; await route.abort(); });
  await page.getByRole("button", { name: "ذخیره محصول", exact: true }).dblclick({ force: true });
  await expect(page.getByRole("button", { name: "در حال ذخیره…" })).toBeDisabled();
  expect(calls).toBe(1); finish();
  await expect(page.locator(".catalog [role=alert]")).toContainText("ارتباط برقرار نشد");
  await expect(page.getByLabel("نام محصول", { exact: true })).toHaveValue("پیراهن لینن");
  await page.unroute(`**${base}`);
  await page.getByRole("button", { name: "ذخیره محصول", exact: true }).click();
  await expect(page.getByRole("region", { name: "کاتالوگ محصولات" }).getByRole("status")).toHaveText("محصول ذخیره شد.");
  const saved = (await (await page.request.get(base)).json()).products[0];
  expect(saved.variants[0].price).toBeNull(); expect(saved.variants[1].price).toBe(480000);
  expect(saved.variants[0].attributes).toEqual({ "رنگ": "آبی" });
  await page.getByRole("button", { name: "تأیید صریح محصول ذخیره‌شده" }).click();
  await expect(page.getByRole("region", { name: "کاتالوگ محصولات" }).getByRole("status")).toHaveText("محصول تأیید شد.");
  await page.getByLabel("نام محصول", { exact: true }).fill("پیراهن لینن تابستانی");
  await page.getByLabel("نام محصول", { exact: true }).press("Tab");
  expect(await page.evaluate(() => document.activeElement?.tagName)).toBe("INPUT");
  await page.getByRole("button", { name: "ذخیره محصول", exact: true }).click();
  await expect(page.getByRole("region", { name: "کاتالوگ محصولات" }).getByRole("status")).toHaveText("محصول ذخیره شد.");
  await page.getByRole("button", { name: "بارگیری مجدد محصول و تاریخچه" }).click();
  await page.getByText("تاریخچهٔ تغییرات", { exact: true }).click();
  await expect(page.locator("details")).toContainText("نسخهٔ ۳");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(await page.locator("html").getAttribute("dir")).toBe("rtl");
  await page.screenshot({ path: `test-results/catalog-${width}.png`, fullPage: true });
  // A server-side edit makes the open form stale; no false success or lost update.
  const current = (await (await page.request.get(`${base}/${saved.id}`)).json()).product;
  expect((await page.request.post(`${base}/${saved.id}`, { headers: mutationHeaders, data: { name: "ویرایش هم‌زمان", variants: current.variants, revision: current.revision } })).status()).toBe(200);
  await page.getByLabel("نام محصول", { exact: true }).fill("نسخه قدیمی");
  await page.getByRole("button", { name: "ذخیره محصول", exact: true }).click();
  await expect(page.locator(".catalog [role=alert]")).toContainText("نسخهٔ محصول تغییر کرده");
  await page.getByRole("button", { name: "بارگیری مجدد محصول و تاریخچه" }).click();
  await expect(page.getByLabel("نام محصول", { exact: true })).toHaveValue("ویرایش هم‌زمان");
  await page.getByRole("button", { name: "بستن فرم" }).click();
  await page.getByLabel("جست‌وجوی نام یا کد").fill("LINEN-BLUE"); await page.getByRole("button", { name: "جست‌وجو", exact: true }).click();
  await expect(page.locator(".catalog-list")).toContainText("ویرایش هم‌زمان");
  await page.route("**/api/stores/*/products?*", route => route.abort());
  await page.getByRole("button", { name: "جست‌وجو", exact: true }).click();
  await expect(page.locator(".catalog [role=alert]")).toContainText("کاتالوگ دریافت نشد");
  await page.unroute("**/api/stores/*/products?*"); await page.getByRole("region", { name: "کاتالوگ محصولات" }).getByRole("button", { name: "تلاش دوباره" }).click();
  await expect(page.locator(".catalog [role=alert]")).toHaveCount(0);
  await page.getByRole("button", { name: "مشاهده و ویرایش" }).click();
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: "بایگانی محصول", exact: true }).click();
  await expect(page.getByRole("region", { name: "کاتالوگ محصولات" }).getByRole("status")).toContainText("محصول بایگانی شد");
  expect((await page.request.post(base, { headers: mutationHeaders, data: { name: "محصول دیگر", variants: [{ name: "ساده", code: "LINEN-BLUE", price: null, attributes: {} }] } })).status()).toBe(409);
  await page.getByRole("button", { name: "ثبت محصول دستی" }).click();
  await page.getByLabel("نام محصول", { exact: true }).fill("محصول دیگر");
  await page.getByLabel("نام تنوع", { exact: true }).fill("ساده");
  await page.getByLabel("کد اختیاری").fill("LINEN-BLUE");
  await page.getByRole("button", { name: "ذخیره محصول", exact: true }).click();
  await expect(page.locator(".catalog [role=alert]")).toContainText("این کد قبلاً استفاده شده");
});
