import { expect, test } from "@playwright/test";
import { randomUUID } from "node:crypto";

for (const width of [360, 1280]) test(`post multi-selection and recovery at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 960 });
  await page.goto("/login");
  const origin = new URL(page.url()).origin;
  const credentials = { username: `post_${randomUUID().replaceAll("-", "").slice(0, 12)}`, password: "posts-password-12345" };
  expect((await page.request.post("/api/auth/register", { data: credentials })).status()).toBe(201);
  expect((await page.request.post("/api/auth/login", { headers: { Origin: origin }, data: credentials })).status()).toBe(200);
  const me = await (await page.request.get("/api/me")).json();
  const headers = { Origin: origin, "X-CSRF-Token": me.csrfToken };
  const { store } = await (await page.request.post("/api/stores", { headers, data: { name: "پوشاک نارون" } })).json();
  const { state } = await (await page.request.post(`/api/stores/${store.id}/connection/start`, { headers, data: {} })).json();
  expect((await page.request.post(`/api/stores/${store.id}/connection/callback`, { headers, data: { state, code: width === 360 ? "demo-page" : "other-page" } })).status()).toBe(200);
  await page.goto("/dashboard/products");
  const browser = page.getByRole("region", { name: "مرور پست‌ها" });
  await expect(browser.getByRole("checkbox")).toHaveCount(6);
  await browser.getByRole("checkbox").nth(0).focus();
  await page.keyboard.press("Space");
  await browser.getByRole("checkbox").nth(1).check();
  await browser.getByRole("button", { name: "پست‌های بعدی" }).click();
  await expect(browser.getByRole("checkbox")).toHaveCount(2);
  await browser.getByRole("checkbox").first().check();
  await expect(browser.locator(".post-actions")).toContainText("۳ پست");
  await page.route("**/post-selections", route => route.abort());
  await browser.getByRole("button", { name: "ذخیرهٔ انتخاب‌ها" }).click();
  await expect(browser.getByRole("alert")).toContainText("انتخاب‌ها تأیید نشدند");
  await page.unroute("**/post-selections");
  await browser.getByRole("button", { name: "ذخیرهٔ انتخاب‌ها" }).click();
  await expect(browser.getByRole("status").filter({ hasText: "انتخاب‌ها ذخیره شدند" })).toBeVisible();
  await expect(browser.getByRole("checkbox").first()).toBeDisabled();
  await page.reload();
  await expect(browser.getByRole("checkbox").nth(0)).toBeChecked();
  await expect(browser.getByRole("checkbox").nth(1)).toBeChecked();
  await expect(browser.getByText("در انتظار پردازش", { exact: true })).toHaveCount(2);
  const stored = await (await page.request.get(`/api/stores/${store.id}/post-selections`)).json();
  expect(stored.selections).toHaveLength(3);
  expect((await page.request.post(`/api/stores/${store.id}/post-selections`, { headers: { Origin: origin }, data: { postIds: ["demo-page-post-03"], key: "no-csrf-test" } })).status()).toBe(403);
  expect(await page.locator("html").getAttribute("dir")).toBe("rtl");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: `test-results/posts-${width}.png`, fullPage: true });
  await page.route("**/posts?*", route => route.fulfill({ status: 503, json: { code: "posts_unavailable" } }));
  await browser.getByRole("button", { name: "تازه‌سازی وضعیت" }).click();
  await expect(browser.getByRole("alert")).toContainText("پست‌ها دریافت نشدند");
  await page.unroute("**/posts?*");
  await browser.getByRole("button", { name: "تلاش دوباره" }).click();
  await expect(browser.getByRole("checkbox")).toHaveCount(6);
  await page.route("**/posts?*", route => route.fulfill({ status: 200, json: { posts: [], nextCursor: "" } }));
  await browser.getByRole("button", { name: "تازه‌سازی وضعیت" }).click();
  await expect(browser.getByRole("heading", { name: "پستی در این صفحه نیست" })).toBeVisible();
  await expect(browser.getByRole("button", { name: "تازه‌سازی فهرست" })).toBeVisible();
  await page.unroute("**/posts?*");
  let release!: () => void;
  const pending = new Promise<void>(resolve => { release = resolve; });
  await page.route("**/posts?*", async route => { await pending; await route.continue(); });
  await browser.getByRole("button", { name: "تازه‌سازی فهرست" }).click();
  await expect(browser.getByRole("status")).toHaveText("در حال دریافت پست‌ها…");
  release();
  await expect(browser.getByRole("checkbox")).toHaveCount(6);
  expect((await page.request.post(`/api/stores/${store.id}/connection/disconnect`, { headers, data: {} })).status()).toBe(200);
});
